import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const common = {
	banner: {
		js: banner,
	},
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	minify: prod,
};

/**
 * 两个产物：
 * 1. main.js            —— 独立插件形态（Obsidian 直接加载）
 * 2. xxljob-bundle.cjs  —— 子模块形态，供 Schema Studio 里 require('./xxljob-bundle.cjs') 集成
 */
const targets = [
	{ entryPoints: ["src/main.ts"], outfile: "main.js" },
	{ entryPoints: ["src/bundle.ts"], outfile: "xxljob-bundle.cjs" },
];

if (prod) {
	for (const t of targets) {
		await esbuild.build({ ...common, ...t });
	}
	process.exit(0);
} else {
	for (const t of targets) {
		const ctx = await esbuild.context({ ...common, ...t });
		await ctx.watch();
	}
}
